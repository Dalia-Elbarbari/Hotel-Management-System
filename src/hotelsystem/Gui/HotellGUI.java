// Logic for confirming a new room booking
    private void ConfirmBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ConfirmBookActionPerformed
        String name = ClientName.getText().trim();

        // Check if the name contains only letters and spaces (no numbers allowed)
        if (!name.matches("^[a-zA-Z\\s]+$")) {
            JOptionPane.showMessageDialog(this, "Invalid Name! Please use letters only (no numbers).");
            return;
        }

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the Client Name!");
            return;
        }
        String room = roomNo.getSelectedItem().toString();
        try {
            // Get the table model to manipulate data
            model = (DefaultTableModel) empTable.getModel();

            // Add a new row with booking details: [ID, Name, Room, Dates, Status]
            model.addRow(new Object[]{
                model.getRowCount() + 1,
                name,
                room,
                "22-04-2026",
                "25-04-2026",
                "Confirmed"
            });

            // Notify the user that the operation was successful
            JOptionPane.showMessageDialog(this, "Booking confirmed for " + name);

            // Clear input fields for the next booking
            ClientName.setText("");
            roomNo.setSelectedIndex(0);

        } catch (Exception e) {
            // Catch any unexpected errors and display them to the user
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }

    }//GEN-LAST:event_ConfirmBookActionPerformed
