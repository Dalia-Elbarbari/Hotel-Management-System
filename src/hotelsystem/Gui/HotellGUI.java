    /**
     * Creates new form HotellGUI Changed to Default Constructor to fix Login
     * errors and use Session management
     */
    public HotellGUI() {
        initComponents();

        // Retrieve the current logged-in user from the Global Holder
        this.currentUser = CurrentUserHolder.getUser();

        // Determine the Role based on the User object data
        if (currentUser != null) {
            try {
                // Convert role string (e.g., "Admin") to the matching Enum constant
                this.currentUserRole = UserRole.valueOf(currentUser.getRole().toUpperCase());
            } catch (Exception e) {
                // Fallback to Guest if role is unrecognized
                this.currentUserRole = UserRole.GUEST;
            }
        } else {
            // Default to Guest if no user session is found
            this.currentUserRole = UserRole.GUEST;
        }

        // Initialize table and apply UI restrictions based on role
        model = (DefaultTableModel) showroomsTable.getModel();
        model.setRowCount(0);
        applyPermissions();

        // Center the window on the screen
        this.setLocationRelativeTo(null);
    }

    /**
     * This method controls the visibility of UI components (buttons/panels)
     * based on the user's permissions.
     */
    private void applyPermissions() {
        if (currentUserRole == null) {
            return;
        }

        switch (currentUserRole) {
            case ADMIN:
                // Admins have full access; no components are hidden
                 EmployeeSide.setVisible(true);
                
                 
                break;

            case EMPLOYEE:
                // Employees are restricted from modifying the room catalog
                EmployeeSide.setVisible(true);
                AddRoom.setVisible(true);
                DeleteRoom.setVisible(true);
           
           
                break;

            case GUEST:
                // Guests have read-only access to rooms and cannot see management tools
                mngRoom.setVisible(false);
                AddRoom.setVisible(false);
                DeleteRoom.setVisible(false);
                EditRoom.setVisible(false);

         
                
                break;
        }

    }

