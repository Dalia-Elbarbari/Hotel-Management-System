    private void loadTable() {
model.setRowCount(0);

    for (Room r : roomList) {
        model.addRow(new Object[]{
            r.getRoomNumber(),
            r.getRoomType(),
            r.getPricePerNight(),
            r.getCapacity(),
            r.isAvailable(),
            r.isHasWifi(),
            r.isHasTV(),
            r.isHasAC()
        });
    
}
}
  
    private void refreshTable() {

    model.setRowCount(0); 

    for (Room r : roomList) {
        model.addRow(new Object[]{
            r.getRoomNumber(),
            r.getPricePerNight(),
            r.isAvailable()
        });
    }
}
    
