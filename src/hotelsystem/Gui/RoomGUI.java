    private void btnAddRoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddRoomActionPerformed
   try {

        int roomNo = Integer.parseInt(txtRoomNumber.getText());
        double price = Double.parseDouble(txtPrice.getText());
        int capacity = Integer.parseInt(txtCapacity.getText());

        RoomType type = RoomType.valueOf(cmbRoomType.getSelectedItem().toString());

        boolean wifi = chkWifi.isSelected();
        boolean tv = chkTV.isSelected();
        boolean ac = chkAC.isSelected();

        Room room = new Room(roomNo, type, price, capacity, wifi, tv, ac);

        roomList.add(room);

        Room.saveRooms(roomList);
        loadTable();

        JOptionPane.showMessageDialog(this, "Room added successfully!");

    } catch (InvalidPriceException e) {
        JOptionPane.showMessageDialog(this, "Invalid price!");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid input!");
    }
    }//GEN-LAST:event_btnAddRoomActionPerformed

    private void bookBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bookBtnActionPerformed
        

    int roomNo = Integer.parseInt(txtRoomNumber.getText());

    boolean found = false;

    for (Room r : roomList) {
        if (r.getRoomNumber() == roomNo) {

            if (r.bookRoom()) {
                JOptionPane.showMessageDialog(this, "Room booked successfully");
            } else {
                JOptionPane.showMessageDialog(this, "Room already booked");
            }

            found = true;
            break;
        }
    }

    if (!found) {
        JOptionPane.showMessageDialog(this, "Room not found");
    }

    loadTable();
        
    }//GEN-LAST:event_bookBtnActionPerformed

    private void updatePriceBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updatePriceBtnActionPerformed
     try {

        int roomNo = Integer.parseInt(txtRoomNumber.getText());
        double price = Double.parseDouble(txtPrice.getText());

        boolean found = false;

        for (Room r : roomList) {
            if (r.getRoomNumber() == roomNo) {

                // THIS can throw exception → MUST be caught
                r.setPricePerNight(price);

                found = true;
                break;
            }
        }

        if (found) {
            loadTable();
            Room.saveRooms(roomList);
            JOptionPane.showMessageDialog(this, "Price updated successfully!");
        } else {
            JOptionPane.showMessageDialog(this, "Room not found!");
        }

    } catch (InvalidPriceException e) {
        JOptionPane.showMessageDialog(this, "Invalid price: must be > 0");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Please enter valid numbers!");
    }
    }//GEN-LAST:event_updatePriceBtnActionPerformed

    private void releaseBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_releaseBtnActionPerformed
        
    int roomNo = Integer.parseInt(txtRoomNumber.getText());

    boolean found = false;

    for (Room r : roomList) {
        if (r.getRoomNumber() == roomNo) {

            r.releaseRoom();
            JOptionPane.showMessageDialog(this, "Room released successfully");

            found = true;
            break;
        }
    }

    if (!found) {
        JOptionPane.showMessageDialog(this, "Room not found");
    }

    loadTable();
    }//GEN-LAST:event_releaseBtnActionPerformed

    private void resetbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_resetbtnActionPerformed
        
    roomList.clear(); 

   
    Room.saveRooms(roomList);

    
    DefaultTableModel model = (DefaultTableModel) roomTable.getModel();
    model.setRowCount(0);

    JOptionPane.showMessageDialog(this, "All data has been reset!");
    }//GEN-LAST:event_resetbtnActionPerformed

