    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        try {
            String input = javax.swing.JOptionPane.showInputDialog(this, "Enter Employee ID to search:");

            if (input != null && !input.isEmpty()) {
                int searchID = Integer.parseInt(input);
                boolean found = false;

                txtDisplay.setText("--- Search Result ---\n");

                for (Employeee e : myAdmin.getempList()) {
                    if (e.getUserID() == searchID) {

                        txtDisplay.append("Found Employee:\n");
                        txtDisplay.append("Name: " + e.getUserName() + "\n");
                        txtDisplay.append("ID: " + e.getUserID() + "\n");
                        txtDisplay.append("Salary: " + e.getEmployeeSalary() + "\n");
                        txtDisplay.append("Position: " + e.getEmployeePosition() + "\n");
                        found = true;
                        break;
                    }
                }

                if (!found) {
                    txtDisplay.append("No employee found with ID: " + searchID);
                    javax.swing.JOptionPane.showMessageDialog(this, "Employee not found!");
                }
            }
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid numeric ID.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

