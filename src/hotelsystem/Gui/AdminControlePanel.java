    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:

        try {
            String inputName = txtName.getText().trim();
            String salaryStr = txtSalary.getText().trim();
            String pos = comboPosition.getSelectedItem().toString();

            if (inputName.isEmpty() || salaryStr.isEmpty()) {
                txtDisplay.setText("Warning: Please enter Name and Salary.");
                return;
            }

            double salary = Double.parseDouble(salaryStr);

            if (salary > 1000) {
                Employeee emp = new Employeee(inputName, "test@mail.com", "011", "123", pos, salary);

                myAdmin.addEmployee(emp);

                UserFileManager.saveUsersData();

                txtDisplay.append(inputName + "      " + emp.getUserID() + pos + "    " + " (Saved to file)\n");

                txtName.setText("");
                txtSalary.setText("");

            } else {
                txtDisplay.setText("Error: Salary must be > 1000.");
            }

        } catch (NumberFormatException ex) {
            txtDisplay.setText("Error: Invalid Salary!");
        } catch (Exception ex) {
            txtDisplay.setText("Error: " + ex.getMessage());
        }


    }//GEN-LAST:event_btnAddActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        try {
            String input = javax.swing.JOptionPane.showInputDialog(this, "Enter ID to delete:");

            if (input != null && !input.trim().isEmpty()) {
                int idToDelete = Integer.parseInt(input.trim());

                myAdmin.removeEmployee(idToDelete);

                txtDisplay.setText(" Delete action performed for ID: " + idToDelete);
                txtDisplay.append("\nCheck the console for detailed status.");

                javax.swing.JOptionPane.showMessageDialog(this, "Process completed!");
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid numeric ID.");
        } catch (Exception ex) {
            txtDisplay.setText(" Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

